// Turns journeys.json into the story the journey view plays, using the builder
// that ships with the view and adding what is particular to this example: the
// layouts of its workflows, chosen by hand, and a sentence for each of its events.
//
//   node examples/claims-journey/make-journeys.mjs
//   node examples/claims-journey/make-story.mjs [out.json]

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { createRequire } from 'module';

const here = path.dirname(fileURLToPath(import.meta.url));
const { build_story } = createRequire(import.meta.url)('../../tools/visualization/journey-story-builder.js');
const sample = JSON.parse(fs.readFileSync(path.join(here, 'journeys.json'), 'utf-8'));
const out = process.argv[2] || path.join(here, 'story.json');
const plural = (n, word) => `${n} ${word}${n === 1 ? '' : 's'}`;

const GRID = {
    'Claim Intake': {
        'Claim submitted': [0, 0], 'Register claim': [1, 0], 'Request documents': [2, 0], 'Documents uploaded': [3, 0],
        'Check completeness': [5, 0], 'Claim registered': [6, 0], 'Intake done': [7, 0],
        'Send reminder': [4, 1], 'Reminder answered': [5, 1], 'Close as incomplete': [6, 1],
    },
    'Motor Claim Settlement': {
        'Claim received': [0, 1], 'Register claim': [1, 1], 'Assess damage': [2, 1], 'Check fraud signals': [3, 0], 'Verify policy cover': [3, 2],
        'Consolidate findings': [4, 1], 'Settlement route': [5, 1], 'Adjuster review': [5, 0], 'Investigate': [5, 2],
        'Reserve funds': [6, 1], 'Release funds': [6, 2], 'Bank cut-off': [7, 1], 'Pay claimant': [8, 1], 'Notify claimant': [9, 1], 'Claim closed': [10, 1],
    },
    'Policy Purchase': {
        'Quote requested': [0, 0], 'Prepare quote': [1, 0], 'Quote accepted': [2, 0], 'Send contract': [3, 0], 'Contract signed': [4, 0], 'Send invoice': [5, 0],
        'Payment received': [6, 0], 'Issue certificate': [7, 0], 'Policy issued': [8, 0], 'Purchase done': [9, 0], 'Expire quote': [8, 1],
    },
    'Policy Renewal': {
        'Renewal due': [0, 0], 'Renewal terms': [1, 0], 'Send renewal offer': [2, 0], 'Renewal paid': [3, 0], 'Issue renewal certificate': [5, 0], 'Policy renewed': [6, 0], 'Renewal done': [7, 0],
        'Send last reminder': [4, 1], 'Paid after reminder': [5, 1], 'Lapse policy': [6, 1], 'Policy lapsed': [7, 1],
    },
    'Customer Follow-up': {
        'Send survey': [0, 0], 'Survey answered': [1, 0], 'How satisfied': [2, 0], 'Thank customer': [3, 0], 'Follow-up done': [4, 0],
        'Call back': [3, 1], 'Record no response': [1, 1],
    },
};

const EVENT_SENTENCE = {
    'claim.submitted': (n, d) => [`Claim reported`, `${n} reports a claim. ${d.description}`],
    'documents.uploaded': (n, d) => [`Documents uploaded`, `${n} uploads ${plural(d.documents, 'document')}.`],
    'survey.answered': (n, d) => [`Survey answered: ${d.satisfaction} of 5`, `${n} answers the survey: ${d.satisfaction} out of 5.${d.comment ? ` “${d.comment}”` : ''}`],
    'claim.withdrawn': (n, d) => [`Claim withdrawn`, `${n} withdraws the claim. ${d.reason || ''}`],
    'quote.requested': (n, d) => [`Quote requested`, `${n} asks for a quote to insure a ${d.vehicle}.`],
    'quote.accepted': n => [`Quote accepted`, `${n} accepts the quote.`],
    'contract.signed': n => [`Contract signed`, `${n} signs the insurance contract.`],
    'payment.received': (n, d) => [`Premium paid`, `${n} pays the premium of EUR ${d.amount}.`],
    'renewal.due': n => [`Renewal due`, `The policy of ${n} is 30 days from its end.`],
    'renewal.paid': n => [`Renewal paid`, `${n} pays the renewal.`],
    'policy.cancelled': (n, d) => [`Policy cancelled`, `${n} calls to cancel the policy. “${d.reason || ''}”`],
};

const story = build_story(sample, { layouts: GRID, sentences: EVENT_SENTENCE });
const journeys = story.journeys;
fs.writeFileSync(out, JSON.stringify(story));
fs.writeFileSync(path.join(here, '../../tools/visualization/journey-story.js'), '// Generated by examples/claims-journey/make-story.mjs. Do not edit.\n' + `window.AWA_STORY = ${JSON.stringify(story)};\n`);

// The same record for the measures page (tools/visualization/dashboard.html), keeping only what the measures read
const pick = (object, keys) => Object.fromEntries(keys.filter(k => object && object[k] !== undefined).map(k => [k, object[k]]));
const RUN_DATA = ['actor_type', 'duration_ms', 'usage', 'cost', 'currency', 'input_tokens', 'output_tokens', 'tool', 'passed', 'verdict', 'method', 'used_default', 'waited_ms', 'workflow_name', 'reason'];
const JOURNEY_DATA = ['sentiment', 'basis', 'channel', 'direction', 'technology', 'reason', 'max_duration', 'owner', 'stage_name'];
const slim = {
    as_of: sample.as_of,
    workflows: sample.workflows.map(w => ({ id: w.id, name: w.name, activities: w.activities.map(a => pick(a, ['id', 'name', 'actor_type'])) })),
    transitions: sample.transitions.map(t => pick(t, ['from', 'to', 'count'])),
    journeys: sample.journeys.map(j => ({
        definition: { ...pick(j.definition, ['id', 'name', 'goals', 'sentiment']), stages: j.definition.stages.map(st => pick(st, ['id', 'name', 'owner', 'max_duration'])) },
        instances: j.instances.map(r => ({
            subject_name: r.subject_name,
            instance: { ...pick(r.instance, ['id', 'journey_id', 'subject_key', 'status', 'stage_id', 'stage_entered_at', 'stalled', 'started_at', 'ended_at', 'goals_reached', 'sentiment', 'stage_history']),
                events: r.instance.events.filter(e => ['journey.started', 'journey.stalled', 'journey.touchpoint', 'journey.sentiment_changed'].includes(e.type))
                    .map(e => ({ ...pick(e, ['type', 'time', 'stage_id']), data: { ...pick(e.data, JOURNEY_DATA), ...(e.data?.artefacts ? { artefacts: e.data.artefacts.map(a => pick(a, ['kind'])) } : {}) } })) },
            runs: r.runs.map(run => ({ ...pick(run, ['run_id', 'workflow_id', 'stage_id']),
                events: run.events.filter(e => !/^(token\.(created|moved|completed|joined|failed|cancelled|waiting)|meta\.|reasoning\.|timer\.|run\.(waiting|resumed)|event\.published)/.test(e.type))
                    .map(e => ({ ...pick(e, ['type', 'time', 'node_id', 'node_name']), data: { ...pick(e.data, RUN_DATA), ...(e.data?.error ? { error: pick(e.data.error, ['code']) } : {}) } })) })),
        })),
    })),
};
fs.writeFileSync(path.join(here, '../../tools/visualization/dashboard-sample.js'), '// Generated by examples/claims-journey/make-story.mjs. Do not edit.\n' + `window.AWA_PORTFOLIO = ${JSON.stringify(slim)};\n`);

for (const j of journeys) {
    console.log(`\n== ${j.name}: ${j.instances.length} journeys, ${j.all.length} moments, technologies: ${j.technologies.join(', ')}; exchanged: ${j.kinds.join(', ')}`);
    for (const c of j.instances) {
        console.log(`${c.name} (${c.ending.label}), mood ${c.mood_start} -> ${c.mood_end}, ${c.beats.length} beats`);
        if (process.env.VERBOSE) for (const b of c.beats) console.log(`  ${b.gap ? `[${b.gap}] ` : ''}${b.when}  ${b.lane.padEnd(7)} ${b.kind.padEnd(14)} mood ${String(b.mood).padEnd(4)} ${b.tp ? `<${b.tp.channel}/${b.tp.technology}: ${b.tp.artefacts.map(a => a.kind).join(',')}> ` : ''}${b.cap}${b.mood_why ? `  (${b.mood_why.map(w => `${w.change > 0 ? '+' : ''}${w.change} ${w.basis}: ${w.reason}`).join('; ')})` : ''}`);
    }
}
console.log(`\n${(fs.statSync(out).size / 1024).toFixed(0)} KB -> ${path.relative(process.cwd(), out)}`);
